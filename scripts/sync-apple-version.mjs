#!/usr/bin/env node
/**
 * Regenerates `apple/Version.xcconfig` from package.json's `version`
 *
 * The Xcode project's project-level Debug/Release configurations use this xcconfig as their
 * `baseConfigurationReference`, and the four targets carry no version settings of their own, so all
 * of them inherit these values. Run this when bumping the version, and commit the result — the
 * xcconfig is committed so a fresh clone builds without running any script first.
 */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const xcconfigPath = resolve(root, 'apple/Version.xcconfig');

const { version } = JSON.parse(await readFile(resolve(root, 'package.json'), 'utf-8'));
if (!version) throw new Error('package.json has no "version" field');

const match = /^(\d+)\.(\d+)\.(\d+)/.exec(version);
if (!match) throw new Error(`package.json version "${version}" is not major.minor.patch`);
const [, major, minor, patch] = match.map(Number);

// A monotonic integer build number derived from the semver, so CFBundleVersion always increases
// across releases (App Store Connect rejects non-increasing build numbers). The trailing two digits
// are a revision counter, always emitted as `00` and edited by hand: App Store Connect also rejects
// a repeat of a build number it has already seen, even for a rejected build, so re-uploading the
// same MARKETING_VERSION needs `…01`, `…02`, and so on.
const buildNumber = (major * 10000 + minor * 100 + patch) * 100;

await writeFile(
  xcconfigPath,
  `// Generated by \`npm run apple:version\` from package.json.
// Only the last two digits of CURRENT_PROJECT_VERSION are meant to be edited by hand: bump them for
// each re-upload of the same MARKETING_VERSION, since App Store Connect rejects a build number it
// has already seen. Re-running the script resets them to 00.
MARKETING_VERSION = ${version}
CURRENT_PROJECT_VERSION = ${buildNumber}
`
);

console.log(`apple/Version.xcconfig -> MARKETING_VERSION=${version} CURRENT_PROJECT_VERSION=${buildNumber}`);
